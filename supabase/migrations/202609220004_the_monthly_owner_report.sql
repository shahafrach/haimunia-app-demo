begin;

-- THE MONTHLY OWNER REPORT. 202609190002's `owner_report` switch gets the
-- feature it was named for.
--
-- WHAT IT IS. One screen, once a month, for whoever runs the club: seven
-- numbers about the month that just closed, and behind each number the list
-- of people it is made of. It answers the question the club actually asks in
-- the first week of a month - "who is still here, who arrived, who stopped
-- coming, and what is the coaching team carrying" - which no existing surface
-- answers in one place. monthly_club_recaps (202609010002) is the closest and
-- is deliberately something else: it is the CLUB's own published summary,
-- aggregate by construction, and it is read by every member.
--
-- WHY IT IS A SECOND TABLE AND NOT FIVE MORE COLUMNS ON monthly_club_recaps.
-- That table's shape is its privacy guarantee - "no user_id column, no jsonb
-- column, no text column, and no array... there is nowhere for a member name
-- to be written even by a careless future producer" - and the migration that
-- created it says in as many words: "Do not add a top_members, a highlights,
-- or a most_improved column here." This report is club-leadership-only and
-- every one of its numbers is the head of a list of names, so putting it in
-- the members' recap row would either publish those figures to the club or
-- turn that table into one whose audience depends on a policy rather than on
-- its shape. Two tables, two audiences, two shapes.
--
-- THE SAME AGGREGATE-ONLY SHAPE, FOR A DIFFERENT REASON. owner_reports has no
-- user_id, no jsonb, no text column either. Not because it may not name a
-- member - a head coach may - but because a STORED list of "members who
-- stopped attending" is a permanent record of a judgement about a person,
-- growing one row a month forever, readable by whoever holds the role next
-- year. The lists are therefore COMPUTED ON DEMAND by owner_report_members()
-- from the tables that already hold the facts, and nothing but counts is
-- written down. Turn the module off and the lists stop being answerable at
-- all; there is no residue to leak.
--
-- WHO MAY READ IT: head_coach and above (role_rank >= 30), through
-- owner_report_viewer(). A coach may NOT - that is the one role boundary
-- this feature introduces, and it is the reason the gate is a rank rather
-- than is_staff(). "Who stopped coming this month" is a management question
-- about the club's health; a coach's own surfaces (coach_tasks, the welcome
-- queue, the engagement flags) tell them who to call, which is the part of
-- the same data they need to do their job.
--
-- NO MEMBER DATA LEAVES THE CLUB. Every figure and every list is computed in
-- Postgres and returned to one signed-in leader's own screen. Nothing is
-- mailed, exported, posted, or written into a notification body: the
-- notification this migration sends carries three integers and no name. There
-- is no CSV, and adding one is not a small change - it is the first path by
-- which this data could leave a phone.
--
-- GATED IN THE POLICY, NOT ON THE SCREEN. owner_reports_leader_select carries
-- club_feature_enabled('owner_report'), owner_report_list() refuses while the
-- key is off, and owner_report_generate() returns null and writes nothing.
-- So the row in cloud.js's registry loses `planned: true` AND `clientOnly:
-- true`, which is exactly the decision 202609190002 said the building branch
-- would be the one to make. supabase/tests/0121 is what proves it bites.
--
-- GENERATED BY THE EXISTING MONTHLY RECAP JOB, and that is a trigger on
-- monthly_club_recaps rather than a line added to recap_monthly_generate().
-- Both would work; the trigger is chosen because the alternative means
-- `create or replace`-ing a 150-line applied function to add one statement to
-- the end of it, which leaves two copies of those 150 lines in the repository
-- for a reader to diff - the characteristic defect this codebase keeps
-- finding, volunteered. Hanging off the table also covers every path that
-- produces a recap, including a hand-run `select recap_monthly_generate()`
-- and any future scheduler, with nothing to remember.

-- ---------------------------------------------------------------------------
-- 1. Who may read this
-- ---------------------------------------------------------------------------
-- Same shape and the same one-line body as is_staff() and is_admin()
-- (202608280001), one rank apart, and deliberately declared beside them in
-- spirit rather than folded into either: is_staff() is coach-and-above and is
-- bound to by a dozen shipped policies, and widening or narrowing it to serve
-- this feature would move all of them.
--
-- SECURITY INVOKER, like both of its siblings. my_role_code() is the definer
-- function underneath, and it resolves auth.uid()'s own role and nobody
-- else's - which is what makes this safe to call from an RLS policy.
--
-- 30 IS head_coach. staff (40) and owner (60) clear it too, and admin (50)
-- is the other role the club actually uses; 202608280001 records that staff
-- and owner are modelled but not exposed in the UI, so in practice this
-- reads exactly "head coach or admin".
create or replace function public.owner_report_viewer() returns boolean
language sql stable security invoker set search_path = '' as $$
  select coalesce(public.role_rank(public.my_role_code()) >= 30, false);
$$;
revoke all on function public.owner_report_viewer() from public, anon;
grant execute on function public.owner_report_viewer() to authenticated;
comment on function public.owner_report_viewer() is
  'True for head_coach and above (role_rank >= 30), which in this club means the head coach and the admin. The one gate on the monthly owner report - its table policy, its list RPC and its notification audience all resolve through this. Deliberately NARROWER than is_staff(): a coach reads the surfaces that tell them who to call, not the club-health read behind them. Security invoker, like is_staff() and is_admin(), because my_role_code() underneath answers only for auth.uid().';

-- Who hears about a new report. The same two-source admin resolution
-- bug_report_alert_recipients() (202609150005) and mod_alert_recipients()
-- use, one rank lower, and kept as its own function for the reason that one
-- states: "a future change to who moderates cannot silently change who hears
-- about bugs". Same argument here, one door further along. It cannot call
-- owner_report_viewer(): my_role_code() answers for the CALLER, and this runs
-- with no session at all.
create or replace function public.owner_report_recipients() returns setof uuid
language sql stable security definer set search_path = '' as $$
  select p.id
  from public.profiles p
  where p.deleted_at is null
    and (
      p.is_admin
      or exists (
        select 1 from public.invite_redemptions ir
        where ir.user_id = p.id
          and coalesce(public.role_rank(ir.role) >= 30, false)
      )
    )
  order by p.id;
$$;
revoke all on function public.owner_report_recipients() from public, anon, authenticated;
comment on function public.owner_report_recipients() is
  'Every head_coach-and-above account (role_rank >= 30) plus the legacy profiles.is_admin flag - the audience owner_report_generate() notifies. The roster-side twin of owner_report_viewer(), which can only answer for the caller; the two are pinned equal in supabase/tests/0121. Granted to no role.';

-- ---------------------------------------------------------------------------
-- 2. Who the report may name
-- ---------------------------------------------------------------------------
-- ONE predicate, referenced by all seven metrics below rather than copied
-- into each - "a right line with three copies, one of which was missed" is
-- this codebase's characteristic defect and seven branches of one function is
-- exactly where it would land next.
--
-- A SOFT-DELETED PROFILE IS NOT IN ANY LIST, and that is a deliberate
-- difference from monthly_club_recaps, which counts a departed member's
-- sessions because "they did train that month, and a club total that quietly
-- shrank when somebody left would not be an honest record of the month". That
-- reasoning is right for a club total and wrong here: every figure in this
-- report is the head of a list of people to do something about, and a name
-- nobody can contact is not one of them. The consequence is stated rather
-- than hidden: owner_reports.new_members can be LOWER than
-- monthly_club_recaps.new_members for the same month, and the difference is
-- exactly the members who joined and then deleted their profile.
--
-- STAFF ARE NOT EXCLUDED, unlike coach_task_members(). A coach who trains is
-- a member who trained, and "active members this month" that silently omitted
-- the coaching team would misreport the club. The at-risk and task lists
-- inherit whatever their own source tables hold.
create or replace function public.owner_report_subject(p_uid uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles pr where pr.id = p_uid and pr.deleted_at is null);
$$;
revoke all on function public.owner_report_subject(uuid) from public, anon, authenticated;
comment on function public.owner_report_subject(uuid) is
  'Is this someone the owner report may name: a profile that exists and has not been soft-deleted. The single membership predicate behind all seven metrics of owner_report_members(), referenced rather than copied. Granted to no role.';

-- ---------------------------------------------------------------------------
-- 3. The seven metrics, each stated exactly once
-- ---------------------------------------------------------------------------
-- THE LIST IS THE DEFINITION AND THE NUMBER IS ITS COUNT. That is the whole
-- structural decision of this file. "Each number links to the list behind it"
-- is a promise that can be broken in one way - by computing the number one
-- way and the list another - and the only way to make it unbreakable is to
-- have one query and derive the figure from it. owner_report_generate() calls
-- this function and counts; owner_report_list() calls this function and
-- names. There is no second copy of any rule.
--
-- EVERY METRIC IS FROZEN ONCE THE MONTH CLOSES, except at_risk. The five
-- month-scoped metrics read only rows stamped inside [month, next month), so
-- re-running the generator for a closed month produces the same figures. Two
-- are not month-scoped in the same sense and say so:
--   tasks_closed  a task opened in August and closed in September counts in
--                 September, which is where the work happened.
--   at_risk       "the members currently flagged", as of the moment the
--                 report is generated - a NOW figure sitting in a row keyed by
--                 month, and the screen labels it כרגע for that reason. It
--                 moves on every regeneration; the other six do not.
--
-- WHAT "FIRST MONTH" MEANS for strong_start, decided in the open because two
-- readings are defensible. It is the CALENDAR MONTH THE MEMBER JOINED, not
-- their first 30 days. The 30-day reading would mean a member who joined on
-- the 28th has a window that is still open when the report is generated on
-- the 1st, so the figure would keep moving after the month closed and two
-- readings of the same report would disagree. The known cost is stated
-- rather than hidden: somebody who joins on the 28th has three days to reach
-- four sessions and will almost never be counted. The list carries each
-- member's own session count beside their name, so a leader reading a low
-- figure in a month with a late intake can see why.
--
-- WHAT "STOPPED ATTENDING" MEANS: attended at least once in the PREVIOUS
-- calendar month and not once in this one. Both halves are closed intervals
-- by the time the report runs, which is what makes it a fact about the month
-- rather than a fact about today. It is not "has not attended in 30 days" -
-- that is a rolling question, it is what coach_tasks' no_contact rule and the
-- engagement flags are for, and it would give a different answer every time
-- the page was opened.
create or replace function public.owner_report_members(p_month_start date, p_metric text)
returns table(user_id uuid, value integer)
language plpgsql stable security definer set search_path = '' as $$
declare
  v_month date;
  v_next  date;
  v_prev  date;
  v_strong integer;
begin
  v_month := date_trunc('month', p_month_start::timestamp)::date;
  v_next  := (v_month + interval '1 month')::date;
  v_prev  := (v_month - interval '1 month')::date;
  -- The one tunable number in this feature, through the reader 202609220002
  -- built for exactly this and which falls back rather than raising on an
  -- admin's typo.
  v_strong := public.club_feature_number('owner_report', 'strong_start_sessions', 4, 1, 30)::integer;

  -- `value` carries a different, named thing per metric. It is what the list
  -- shows beside each name and, for the two task metrics, what the headline
  -- figure is summed from. Documented per branch; never read by a predicate.

  if p_metric = 'active' then
    -- Attendance DAYS this month. attendance_log is unique on
    -- (user_id, occurred_on), so a row count is a count of training days.
    return query
      select al.user_id, count(*)::integer
        from public.attendance_log al
       where al.occurred_on >= v_month and al.occurred_on < v_next
         and public.owner_report_subject(al.user_id)
       group by al.user_id;

  elsif p_metric = 'new' then
    -- invite_redemptions.redeemed_at is this module's authoritative
    -- MEMBER_JOINED timestamp (202608290011), and it is what
    -- recap_monthly_generate() counts, so the two figures answer the same
    -- question. `value` is the number of training days they logged in their
    -- first month - the single most useful thing to see beside a new name.
    --
    -- The limitation recap_monthly_generate() flags is inherited unchanged
    -- and cannot be fixed from here: grant_coach_role() UPDATEs
    -- invite_redemptions and moves redeemed_at, so promoting an existing
    -- member to coach re-dates them into the month of the promotion.
    return query
      select ir.user_id,
             (select count(*)::integer from public.attendance_log al
               where al.user_id = ir.user_id
                 and al.occurred_on >= v_month and al.occurred_on < v_next)
        from public.invite_redemptions ir
       where ir.redeemed_at >= v_month::timestamptz
         and ir.redeemed_at <  v_next::timestamptz
         and public.owner_report_subject(ir.user_id);

  elsif p_metric = 'stopped' then
    -- `value` is how many days they trained in the month they were last
    -- seen, which is what says whether this is a regular who vanished or
    -- somebody who came once.
    return query
      select al.user_id, count(*)::integer
        from public.attendance_log al
       where al.occurred_on >= v_prev and al.occurred_on < v_month
         and public.owner_report_subject(al.user_id)
         and not exists (
           select 1 from public.attendance_log a2
            where a2.user_id = al.user_id
              and a2.occurred_on >= v_month and a2.occurred_on < v_next)
       group by al.user_id;

  elsif p_metric = 'strong_start' then
    -- A strict subset of 'new', by construction: the same membership clause,
    -- the same window, plus the threshold. `value` is their session count,
    -- so a leader can see who cleared the bar by how much.
    return query
      select ir.user_id,
             (select count(*)::integer from public.attendance_log al
               where al.user_id = ir.user_id
                 and al.occurred_on >= v_month and al.occurred_on < v_next)
        from public.invite_redemptions ir
       where ir.redeemed_at >= v_month::timestamptz
         and ir.redeemed_at <  v_next::timestamptz
         and public.owner_report_subject(ir.user_id)
         and (select count(*) from public.attendance_log al
               where al.user_id = ir.user_id
                 and al.occurred_on >= v_month and al.occurred_on < v_next) >= v_strong;

  elsif p_metric = 'tasks_opened' then
    -- ONE ROW PER MEMBER, `value` = how many tasks of theirs opened this
    -- month. The headline figure is the SUM, not the count, because "coach
    -- tasks opened" is a count of tasks; the list behind it is the members
    -- those tasks are about. The screen says both numbers for that reason.
    return query
      select t.user_id, count(*)::integer
        from public.coach_tasks t
       where t.opened_at >= v_month::timestamptz
         and t.opened_at <  v_next::timestamptz
         and public.owner_report_subject(t.user_id)
       group by t.user_id;

  elsif p_metric = 'tasks_closed' then
    return query
      select t.user_id, count(*)::integer
        from public.coach_tasks t
       where t.closed_at >= v_month::timestamptz
         and t.closed_at <  v_next::timestamptz
         and public.owner_report_subject(t.user_id)
       group by t.user_id;

  elsif p_metric = 'at_risk' then
    -- coach_engagement_flags with status 'open' is what "currently flagged"
    -- means in this schema (202608280011). DISTINCT ON because a member can
    -- carry more than one open flag and a list that named somebody twice
    -- would also count them twice. `value` is how many days the newest flag
    -- has been open - the number that says whether this is news or a
    -- standing problem.
    return query
      select distinct on (f.user_id)
             f.user_id, (current_date - f.flagged_at::date)::integer
        from public.coach_engagement_flags f
       where f.status = 'open'
         and public.owner_report_subject(f.user_id)
       order by f.user_id, f.flagged_at desc;
  end if;
  -- An unknown metric returns no rows. owner_report_list() raises on one
  -- before it gets here; owner_report_generate() only ever passes the seven.
end $$;
revoke all on function public.owner_report_members(date, text) from public, anon, authenticated;
comment on function public.owner_report_members(date, text) is
  'The seven owner-report metrics, each stated exactly once, as (user_id, value) rows. Granted to no role: it reads attendance_log, invite_redemptions, coach_tasks and coach_engagement_flags past their own RLS, so a client-callable version would be a general-purpose reader of all four. owner_report_generate() counts these rows into a figure and owner_report_list() names them, which is what makes "the number and the list behind it" impossible to disagree. Metrics: active, new, stopped, strong_start, tasks_opened, tasks_closed, at_risk. `value` means something different per metric - training days for active/stopped, first-month sessions for new/strong_start, tasks for the two task metrics, days since flagging for at_risk. Only at_risk is a NOW figure; the other six are frozen once the month closes.';

-- ---------------------------------------------------------------------------
-- 4. The table
-- ---------------------------------------------------------------------------
create table public.owner_reports (
  id uuid primary key default gen_random_uuid(),
  club_id uuid not null default public.default_club_id() references public.clubs(id),

  -- The same load-bearing CHECK monthly_club_recaps.month_start carries, for
  -- the same reason: the unique key is what makes generation idempotent per
  -- month, and a key on a free-form date is only unique per date.
  month_start date not null unique check (extract(day from month_start) = 1),

  -- The recap this report was generated alongside. Nullable because the
  -- report can be produced for a month whose recap row has since been
  -- deleted, and null is more honest than refusing to keep the figures.
  recap_id uuid references public.monthly_club_recaps(id) on delete set null,

  -- The seven figures. Five are counts of members, two are counts of TASKS -
  -- see owner_report_members()' tasks_opened branch for why the task figures
  -- are a sum over the list rather than its length.
  active_members       integer not null default 0 check (active_members >= 0),
  new_members          integer not null default 0 check (new_members >= 0),
  stopped_members      integer not null default 0 check (stopped_members >= 0),
  strong_start_members integer not null default 0 check (strong_start_members >= 0),
  coach_tasks_opened   integer not null default 0 check (coach_tasks_opened >= 0),
  coach_tasks_closed   integer not null default 0 check (coach_tasks_closed >= 0),
  at_risk_members      integer not null default 0 check (at_risk_members >= 0),

  generated_at timestamptz not null default now(),
  -- Set once, by the generator, the first time this month's report exists.
  -- It is what makes "announce a report once" a property of the row rather
  -- than of the generator remembering whether it just inserted or updated.
  notified_at timestamptz
);

-- DB-M3 (202609060012, pinned as a property over the whole catalog by
-- supabase/tests/0081): every foreign key column outside club_id leads an
-- index. month_start's unique constraint already indexes the only other
-- column anything sorts or filters on, and there is no user_id column here
-- at all to need one - which is the aggregate-only shape doing a second job.
create index owner_reports_recap_idx on public.owner_reports(recap_id);

alter table public.owner_reports enable row level security;
revoke all on public.owner_reports from public, anon;
-- SELECT ONLY, for everybody. No insert, update or delete grant and no write
-- policy for any client role - not for a coach, not for the head coach, not
-- for the admin, not for the owner. owner_report_generate() is the only
-- writer, the same shape monthly_club_recaps, attendance_log and coach_tasks
-- all use. A report an admin could hand-edit is not a report.
grant select on public.owner_reports to authenticated;

-- ONE policy, not two. monthly_club_recaps has two because it has two
-- audiences; this table has one, and a second permissive policy here would
-- be a second place for the audience to widen by accident.
create policy owner_reports_leader_select on public.owner_reports
  for select to authenticated
  using (
    public.owner_report_viewer()
    and club_id = public.default_club_id()
    and public.club_feature_enabled('owner_report')
  );

comment on table public.owner_reports is
  'One row per calendar month of club-leadership figures: active members, new members, members who stopped attending, new members who reached the strong-start threshold, coach tasks opened and closed, and members currently flagged at risk. AGGREGATE-ONLY BY SHAPE - no user_id, no jsonb, no text column - so the LISTS behind these numbers are computed on demand by owner_report_members() and never stored: a permanent, growing record of "members who stopped attending" is not a thing this club keeps. Read by head_coach and above only (owner_report_viewer()), for their own club, and only while club_feature_enabled(''owner_report'') - all three in the one select policy, which is what makes the module key a server gate rather than a screen hide. No client write grant of any kind: owner_report_generate() is the only writer, and it runs from a trigger on monthly_club_recaps so the existing monthly recap job produces it.';

comment on column public.owner_reports.at_risk_members is
  'The number of members carrying an OPEN coach_engagement_flags row at the moment the report was generated - a now figure, not a month figure, and the only one of the seven that moves when a closed month is regenerated. The screen labels it accordingly.';
comment on column public.owner_reports.coach_tasks_opened is
  'A count of TASKS, not of members: the sum over owner_report_members(month, ''tasks_opened''), whose rows are one per member with that member''s own count. The list behind this number is therefore shorter than the number whenever anyone carried two tasks.';
comment on column public.owner_reports.notified_at is
  'When the head coaches and admins were told this report existed. Null means they have not been. Set once by owner_report_generate(); a regeneration refreshes the figures and does NOT re-announce, which is what keeps a month to one notification however many times the recap job runs.';

-- ---------------------------------------------------------------------------
-- 5. Generation
-- ---------------------------------------------------------------------------
-- AUTH: the documented scheduled-job shape - security definer, granted to
-- service_role and nobody else, and no auth.uid() check, because the caller
-- is a trigger firing inside the monthly recap job and has no session. The
-- grant is the gate, exactly as it is for recap_monthly_generate().
--
-- THE MODULE GATE IS THE FIRST LINE. With owner_report off, nothing is
-- computed and nothing is written - so a club that has not switched this on
-- has no owner_reports rows at all, not merely unreadable ones.
--
-- IDEMPOTENT PER CALENDAR MONTH, in one statement, the same
-- `on conflict (month_start) do update` recap_monthly_generate() uses. There
-- is no `where published_at is null` equivalent because there is no publish
-- step: this report is never shown to a member, so there is nothing to
-- freeze and a refreshed at_risk figure is the point rather than a hazard.
create or replace function public.owner_report_generate(p_month_start date default null)
returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_month date;
  v_id uuid;
  v_recap uuid;
  v_notified timestamptz;
  v_active integer;
  v_new integer;
  v_stopped integer;
  v_strong integer;
  v_opened integer;
  v_closed integer;
  v_risk integer;
  v_recipient uuid;
begin
  if not public.club_feature_enabled('owner_report') then return null; end if;

  -- Null means the most recently COMPLETED calendar month, and any other date
  -- is normalised to the first of its own month - the same two courtesies
  -- recap_monthly_generate() extends, so the two functions can never disagree
  -- about which month a bare call means.
  v_month := date_trunc('month',
               coalesce(p_month_start, (current_date - interval '1 month')::date)::timestamp
             )::date;

  select count(*)::integer                into v_active  from public.owner_report_members(v_month, 'active');
  select count(*)::integer                into v_new     from public.owner_report_members(v_month, 'new');
  select count(*)::integer                into v_stopped from public.owner_report_members(v_month, 'stopped');
  select count(*)::integer                into v_strong  from public.owner_report_members(v_month, 'strong_start');
  -- SUM, not count: see the column comment and owner_report_members()'
  -- tasks_opened branch.
  select coalesce(sum(m.value), 0)::integer into v_opened from public.owner_report_members(v_month, 'tasks_opened') m;
  select coalesce(sum(m.value), 0)::integer into v_closed from public.owner_report_members(v_month, 'tasks_closed') m;
  select count(*)::integer                into v_risk    from public.owner_report_members(v_month, 'at_risk');

  select r.id into v_recap from public.monthly_club_recaps r where r.month_start = v_month;

  insert into public.owner_reports
    (month_start, recap_id, active_members, new_members, stopped_members,
     strong_start_members, coach_tasks_opened, coach_tasks_closed, at_risk_members, generated_at)
  values
    (v_month, v_recap, v_active, v_new, v_stopped,
     v_strong, v_opened, v_closed, v_risk, now())
  on conflict (month_start) do update
    set recap_id             = excluded.recap_id,
        active_members       = excluded.active_members,
        new_members          = excluded.new_members,
        stopped_members      = excluded.stopped_members,
        strong_start_members = excluded.strong_start_members,
        coach_tasks_opened   = excluded.coach_tasks_opened,
        coach_tasks_closed   = excluded.coach_tasks_closed,
        at_risk_members      = excluded.at_risk_members,
        generated_at         = now()
    -- notified_at is in NEITHER the column list nor the SET list. A
    -- regeneration is structurally incapable of re-announcing.
  returning id, notified_at into v_id, v_notified;

  -- ---- the announcement ---------------------------------------------------
  -- ONCE PER MONTH, decided by the column rather than by detecting whether
  -- the statement above inserted or updated. The recap job can run again, an
  -- operator can re-run it by hand, and a leader can be added to the club
  -- mid-month; none of those is a new report.
  --
  -- THREE INTEGERS AND NO NAME. The body is the same aggregate-only
  -- discipline recap_monthly_publish() applies to its own notification, and
  -- here it is the whole "no member data leaves the club" promise in the one
  -- place where text about members is written for delivery: a push
  -- notification is the only part of this feature that lands on a device
  -- without anyone opening the report, so it says how many, never who.
  --
  -- PUSH NEEDS NOTHING HERE. notif_push_pending() (202609170002) picks up any
  -- notifications row whose recipient has explicitly chosen push for that
  -- type's preference key, and notif_pref_key()'s identity fallback makes
  -- that key 'owner_report_ready'. So a head coach who has switched this type
  -- to push in Settings gets a push, and one who has not gets the in-app row
  -- only - which is the same opt-in every other type in this schema has.
  --
  -- NO DEEP LINK, on purpose and for the reason 202609190001's
  -- job_health_alert states: the screen this points at lives in the club
  -- management panel, which is not a Community sub-tab, so
  -- resolveNotifTarget() would land the reader on the feed. A link to the
  -- wrong place is worse than no link.
  if v_notified is null then
    for v_recipient in select * from public.owner_report_recipients() loop
      perform public.notif_create(
        v_recipient,
        'owner_report_ready',
        'club',
        'דוח החודש של המועדון מוכן',
        v_active::text || ' חברים פעילים, ' ||
        v_new::text || ' חדשים ו-' ||
        v_stopped::text || ' שהפסיקו להגיע.',
        'owner_report', v_id, null
      );
    end loop;
    update public.owner_reports set notified_at = now() where id = v_id;
  end if;

  return v_id;
end $$;
revoke all on function public.owner_report_generate(date) from public, anon, authenticated;
grant execute on function public.owner_report_generate(date) to service_role;
comment on function public.owner_report_generate(date) is
  'Produces (or refreshes) the owner_reports row for one calendar month and, the first time that row exists, notifies every owner_report_recipients() account with an ''owner_report_ready'' notification carrying three integers and no member name. service_role only, and no auth.uid() check - the documented scheduled-job exception, because it runs from a trigger on monthly_club_recaps with no session. Returns null and writes nothing at all while club_feature_enabled(''owner_report'') is false. p_month_start null means the most recently COMPLETED month; any other date is normalised to the first of its own month, both matching recap_monthly_generate(). Idempotent per month: the upsert refreshes the seven figures in place and touches neither notified_at nor the row''s identity, so a re-run can never produce a second row or a second announcement.';

-- ---------------------------------------------------------------------------
-- 6. The hook into the existing monthly recap job
-- ---------------------------------------------------------------------------
-- AFTER INSERT OR UPDATE, so the report is produced by whatever produced the
-- recap: the pg_cron `recap_monthly` entry recap_monthly_generate()'s own
-- header documents, a hand-run call by an operator, or a future scheduler.
-- recap_monthly_generate()'s upsert carries `where published_at is null`, so
-- for an already-published month no UPDATE executes and this does not fire -
-- which is the right answer: that month's report already exists.
--
-- ALSO ON UPDATE, which means a publish (the one UPDATE the freeze trigger
-- permits) refreshes the report too. Harmless and slightly useful: the
-- figures are recomputed from the same closed month and come out the same,
-- except at_risk, which is a now figure and is meant to move.
create or replace function public.owner_report_on_recap() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  perform public.owner_report_generate(new.month_start);
  return null;
end $$;
revoke all on function public.owner_report_on_recap() from public, anon, authenticated;

create trigger monthly_club_recaps_generates_owner_report
  after insert or update on public.monthly_club_recaps
  for each row execute function public.owner_report_on_recap();

comment on function public.owner_report_on_recap() is
  'AFTER INSERT OR UPDATE on monthly_club_recaps. Calls owner_report_generate() for the same month, so the monthly owner report is produced by the existing monthly recap job with no edit to recap_monthly_generate() - a trigger rather than a line appended to that 150-line applied function, which would have left two copies of it in the repository. A no-op while club_feature_enabled(''owner_report'') is false, because the generator returns at its first line. Returns NULL (AFTER trigger).';

-- ---------------------------------------------------------------------------
-- 7. The list behind a number
-- ---------------------------------------------------------------------------
-- The only way a member's name reaches a leader's screen in this feature, and
-- the only client-callable function here.
--
-- SECURITY DEFINER for one boundary, the same one coach_tasks_refresh()
-- crosses: attendance_log is own-row-plus-staff, invite_redemptions is
-- own-row, and coach_engagement_flags is staff-minus-yourself, so a head
-- coach cannot assemble any of these lists from the tables themselves. It
-- returns a name and one number, never the rows underneath - the same "a
-- count, not a log" line PRIVACY.md holds this app to and that
-- coach_new_members() and coach_tasks_refresh() both already carry.
--
-- THREE GATES, in order: a session, the rank, and the module. The module one
-- returns EMPTY rather than raising, for the reason coach_tasks_refresh()
-- states - an admin switching a module off in one tab must not turn an open
-- tab into an error toast - while the rank one raises, because a coach
-- reaching this function is not a display state, it is a refusal.
create or replace function public.owner_report_list(
  p_month_start date,
  p_metric text,
  p_limit integer default 200
)
returns table(
  user_id uuid,
  handle text,
  display_name text,
  avatar_url text,
  value integer
)
language plpgsql stable security definer set search_path = '' as $$
declare
  v_limit integer;
  v_month date;
begin
  if auth.uid() is null then raise exception 'not authorized'; end if;
  if not public.owner_report_viewer() then raise exception 'not authorized'; end if;
  if not public.club_feature_enabled('owner_report') then return; end if;
  if p_metric is null or p_metric not in
       ('active', 'new', 'stopped', 'strong_start', 'tasks_opened', 'tasks_closed', 'at_risk') then
    raise exception 'unknown metric %', p_metric;
  end if;
  if p_month_start is null then raise exception 'month required'; end if;

  v_limit := least(greatest(coalesce(p_limit, 200), 1), 500);
  v_month := date_trunc('month', p_month_start::timestamp)::date;

  return query
  select m.user_id,
         pr.handle,
         coalesce(nullif(pr.display_name, ''), pr.handle),
         pr.avatar_url,
         m.value
    from public.owner_report_members(v_month, p_metric) m
    join public.profiles pr on pr.id = m.user_id
  -- Biggest number first, then the handle, so the order is total and two
  -- reads of the same month never differ.
   order by m.value desc nulls last, pr.handle asc
   limit v_limit;
end $$;
revoke all on function public.owner_report_list(date, text, integer) from public, anon;
grant execute on function public.owner_report_list(date, text, integer) to authenticated;
comment on function public.owner_report_list(date, text, integer) is
  'The list behind one number on the monthly owner report: (user_id, handle, display_name, avatar_url, value) for one metric of one month. AUTH: security definer; raises ''not authorized'' (P0001) without a session or for anyone below head_coach, and returns NO rows - not an error - while club_feature_enabled(''owner_report'') is false. Raises ''unknown metric %'' for anything outside the seven and ''month required'' for a null month. Reads owner_report_members(), which is the same query the stored figure was counted from, so a number and its list cannot disagree. Returns a name and one number per member, never the attendance, redemption, task or flag rows underneath. p_limit clamped 1..500.';

commit;
